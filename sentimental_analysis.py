# Analyze the sentiment distribution for each category (positive, negative, neutral)
# using RoBERTa scores

def get_sentiment_label(row):
  """
  Determines the sentiment label based on the RoBERTa scores.
  """
  if row['roberta_pos'] > row['roberta_neg'] and row['roberta_pos'] > row['roberta_neu']:
    return 'Positive'
  elif row['roberta_neg'] > row['roberta_pos'] and row['roberta_neg'] > row['roberta_neu']:
    return 'Negative'
  else:
    return 'Neutral'


results_df['sentiment_label'] = results_df.apply(lambda row: get_sentiment_label(row), axis=1)

# Analyze the distribution of sentiment labels
sentiment_counts = results_df['sentiment_label'].value_counts()
